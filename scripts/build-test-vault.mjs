// Regenerates the sample PDFs in test-vault/PDFs/ from scripts/vault-src/*.typ (SPEC §11).
// Needs `typst` and `qpdf` (both in the flake dev shell). Only ever writes inside test-vault/
// (never .obsidian/), or into a folder under .scratch/ given as an argument.
// Run: npm run vault:reset
import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'scripts', 'vault-src');
const target = process.argv[2] ? resolve(process.argv[2]) : join(root, 'test-vault');
if (target !== join(root, 'test-vault') && !target.startsWith(join(root, '.scratch') + '/')) throw new Error('target must be test-vault/ or inside .scratch/');
const vault = target;

function out(rel) {
	const p = join(vault, rel);
	if (!p.startsWith(vault + '/') || p.includes('/.obsidian/')) throw new Error('refusing to write outside test-vault: ' + p);
	mkdirSync(dirname(p), { recursive: true });
	return p;
}

function typst(source, rel, inputs = {}) {
	const args = ['compile', '--root', src];
	for (const [k, v] of Object.entries(inputs)) args.push('--input', `${k}=${v}`);
	args.push(join(src, source), out(rel));
	execFileSync('typst', args, { stdio: 'inherit' });
	console.log('wrote', rel);
}

rmSync(join(vault, 'PDFs'), { recursive: true, force: true });

typst('lighthouses.typ', 'PDFs/Lighthouses.pdf');
// Same essay, revised: a paragraph added near the start, so anchors must be re-found by quote.
typst('lighthouses.typ', 'PDFs/Lighthouses (revised).pdf', { version: '2' });
typst('paper.typ', 'PDFs/Two-column paper.pdf');
typst('scanned.typ', 'PDFs/Scanned pages.pdf');
typst('book.typ', 'PDFs/Long book.pdf');

// Same name in another folder (note-name collisions in the comments folder, SPEC §5.1).
typst('lighthouses.typ', 'PDFs/Old/Lighthouses.pdf');

// Password-protected copy (user password "test").
execFileSync('qpdf', ['--encrypt', 'test', 'owner', '256', '--', out('PDFs/Lighthouses.pdf'), out('PDFs/Protected (password test).pdf')], { stdio: 'inherit' });
console.log('wrote PDFs/Protected (password test).pdf');

writeFileSync(
	out('Start here.md'),
	`# PDF Comments test vault

Generated by \`npm run vault:reset\` (PDFs are rebuilt from scripts/vault-src/).

- [[PDFs/Lighthouses.pdf]]: essay over several pages, outline, footnotes, internal and external links, a paragraph across a page break.
- [[PDFs/Lighthouses (revised).pdf]]: the same essay with a paragraph added near the start (re-anchoring).
- [[PDFs/Old/Lighthouses.pdf]]: same file name in another folder (note-name collisions).
- [[PDFs/Two-column paper.pdf]]: two columns, abstract, figure, equation, table.
- [[PDFs/Scanned pages.pdf]]: pages with no text layer (area comments).
- [[PDFs/Long book.pdf]]: ~300 pages (performance).
- [[PDFs/Protected (password test).pdf]]: password \`test\`.

Links with subpaths: [[PDFs/Lighthouses.pdf#page=3]], [[PDFs/Long book.pdf#page=150]].
`,
);
console.log('wrote Start here.md');
