import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFileSync, mkdirSync, existsSync, writeFileSync } from 'node:fs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: PDF Comments plugin (src/)
*/
`;

const prod = process.argv[2] === 'production';
const VAULT_PLUGIN_DIR = 'test-vault/.obsidian/plugins/pdf-comments';

/** After every build, copy the release artifacts into the test vault. */
const copyToVault = {
	name: 'copy-to-vault',
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length) return;
			mkdirSync(VAULT_PLUGIN_DIR, { recursive: true });
			copyFileSync('dist/main.js', `${VAULT_PLUGIN_DIR}/main.js`);
			copyFileSync('dist/styles.css', `${VAULT_PLUGIN_DIR}/styles.css`);
			copyFileSync('manifest.json', `${VAULT_PLUGIN_DIR}/manifest.json`);
			// Marker file for the Hot Reload plugin.
			if (!existsSync(`${VAULT_PLUGIN_DIR}/.hotreload`)) writeFileSync(`${VAULT_PLUGIN_DIR}/.hotreload`, '');
			console.log(`[pdf-comments] copied build to ${VAULT_PLUGIN_DIR}`);
		});
	},
};

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: { main: 'src/obsidian/main.ts', styles: 'src/styles/index.css' },
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outdir: 'dist',
	minify: prod,
	plugins: [copyToVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
